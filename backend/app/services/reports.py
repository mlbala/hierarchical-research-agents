"""Report assembly, persistence, retrieval and search.

The report's structure (headings, key-findings list, sources section) is
generated by code; only the prose inside sections comes from the writers, and
that prose is sanitised. The sources list is built from ``report_citations``
so numbering in the text and the list always agree.
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from sqlalchemy import func, select

from app.core.errors import NotFoundError
from app.core.markdown import escape_inline, markdown_link_target, sanitize_markdown
from app.db.engine import Database
from app.db.models import (
    Finding,
    Report,
    ReportCitation,
    ResearchRun,
    Source,
    report_search_vector,
    utcnow,
    web_search_query,
)
from app.services.evidence import EvidenceStore

KIND_LABELS = {
    "fetched_page": "Fetched page",
    "search_snippet": "Search snippet only (page not read)",
    "demo": "Demo fixture (fictional)",
}


@dataclass(frozen=True)
class CitedSource:
    number: int
    source_id: uuid.UUID
    title: str
    url: str
    publisher: str | None
    published_at: datetime | None
    retrieved_at: datetime
    content_kind: str


@dataclass(frozen=True)
class ReportContent:
    title: str
    executive_summary: str
    direct_answer: str
    key_findings: list[str]
    detailed_analysis: str
    limitations: list[str]
    is_partial: bool
    partial_reasons: list[str]
    execution_mode: str


def _source_line(source: CitedSource) -> str:
    title = escape_inline(source.title or source.url)
    target = markdown_link_target(source.url)
    linked = f"[{title}]({target})" if target else title
    parts = [f"{source.number}. {linked}"]
    if source.publisher:
        parts.append(escape_inline(source.publisher))
    if source.published_at:
        parts.append(f"Published {source.published_at.date().isoformat()}")
    parts.append(f"Retrieved {source.retrieved_at.date().isoformat()}")
    parts.append(KIND_LABELS.get(source.content_kind, source.content_kind))
    return " — ".join(parts)


def assemble_body(content: ReportContent, sources: Sequence[CitedSource]) -> str:
    """Build the report body (everything after the executive summary)."""
    lines: list[str] = []
    lines += ["## Direct answer", "", sanitize_markdown(content.direct_answer), ""]
    lines += ["## Key findings", ""]
    lines += [f"- {sanitize_markdown(item).replace(chr(10), ' ')}" for item in content.key_findings]
    lines += ["", "## Detailed analysis", "", sanitize_markdown(content.detailed_analysis), ""]
    lines += ["## Limitations and unresolved questions", ""]
    if content.limitations:
        lines += [
            f"- {sanitize_markdown(item).replace(chr(10), ' ')}" for item in content.limitations
        ]
    else:
        lines.append("- No specific limitations were recorded.")
    lines += ["", "## Sources", ""]
    lines += [_source_line(s) for s in sources]
    return "\n".join(lines).strip() + "\n"


def full_markdown(report: Report, *, execution_mode: str) -> str:
    """The downloadable document: title, banners, summary and body."""
    parts = [f"# {escape_inline(report.title)}", ""]
    if execution_mode == "demo":
        parts += [
            "> **Demo mode:** this report was produced from fictional fixture data. "
            "It is not real research.",
            "",
        ]
    if report.is_partial:
        parts += [
            "> **Partial report:** some planned research could not be completed. See "
            "*Limitations and unresolved questions* for the missing coverage.",
            "",
        ]
    parts += ["## Executive summary", "", report.executive_summary, "", report.body_markdown]
    return "\n".join(parts).rstrip() + "\n"


class ReportService:
    def __init__(self, db: Database) -> None:
        self._db = db

    async def save(
        self,
        run_id: uuid.UUID,
        content: ReportContent,
        citations: Sequence[tuple[int, uuid.UUID]],
    ) -> Report:
        """Persist the report and its citations in one short transaction."""
        async with self._db.session() as session:
            source_ids = [sid for _, sid in citations]
            # Service-layer ownership validation (report_citations has no run_id).
            await EvidenceStore.assert_sources_in_run(session, run_id, source_ids)
            sources = {
                s.id: s
                for s in await session.scalars(
                    select(Source).where(Source.run_id == run_id, Source.id.in_(source_ids))
                )
            }
            cited = [
                CitedSource(
                    number=n,
                    source_id=sid,
                    title=sources[sid].title,
                    url=sources[sid].url,
                    publisher=sources[sid].publisher,
                    published_at=sources[sid].published_at,
                    retrieved_at=sources[sid].retrieved_at,
                    content_kind=sources[sid].content_kind,
                )
                for n, sid in citations
            ]
            now = utcnow()
            report = Report(
                id=uuid.uuid4(),
                run_id=run_id,
                title=content.title.strip()[:300] or "Research report",
                executive_summary=sanitize_markdown(content.executive_summary),
                body_markdown=assemble_body(content, cited),
                limitations=content.limitations,
                is_partial=content.is_partial,
                created_at=now,
                updated_at=now,
            )
            session.add(report)
            await session.flush()
            session.add_all(
                ReportCitation(
                    id=uuid.uuid4(), report_id=report.id, source_id=sid, citation_number=n
                )
                for n, sid in citations
            )
            return report

    async def get_for_run(self, run_id: uuid.UUID) -> dict[str, Any]:
        """Report plus citation details and evidence previews for the UI."""
        async with self._db.session() as session:
            row = (
                await session.execute(
                    select(Report, ResearchRun.execution_mode)
                    .join(ResearchRun, ResearchRun.id == Report.run_id)
                    .where(Report.run_id == run_id)
                )
            ).first()
            if row is None:
                raise NotFoundError("No report exists for this run.")
            report, mode = row
            citation_rows = (
                await session.execute(
                    select(ReportCitation.citation_number, Source)
                    .join(Source, Source.id == ReportCitation.source_id)
                    .where(ReportCitation.report_id == report.id, Source.run_id == run_id)
                    .order_by(ReportCitation.citation_number)
                )
            ).all()
            source_ids = [s.id for _, s in citation_rows]
            findings = list(
                await session.scalars(
                    select(Finding)
                    .where(Finding.run_id == run_id, Finding.source_id.in_(source_ids))
                    .order_by(Finding.created_at)
                )
            )
        evidence: dict[uuid.UUID, list[dict[str, str]]] = {}
        for finding in findings:
            evidence.setdefault(finding.source_id, []).append(
                {
                    "claim": finding.claim,
                    "excerpt": finding.evidence_excerpt,
                    "support_level": finding.support_level,
                }
            )
        return {
            "report": report,
            "execution_mode": mode,
            "citations": [
                {
                    "number": number,
                    "source": source,
                    "evidence": evidence.get(source.id, [])[:3],
                }
                for number, source in citation_rows
            ],
        }

    async def markdown_for_run(self, run_id: uuid.UUID) -> tuple[str, str]:
        async with self._db.session() as session:
            row = (
                await session.execute(
                    select(Report, ResearchRun.execution_mode)
                    .join(ResearchRun, ResearchRun.id == Report.run_id)
                    .where(Report.run_id == run_id)
                )
            ).first()
        if row is None:
            raise NotFoundError("No report exists for this run.")
        report, mode = row
        return report.title, full_markdown(report, execution_mode=mode)

    async def search(self, query: str, *, limit: int, offset: int) -> tuple[list[Any], int]:
        """Full-text search across saved reports (title, summary and body)."""
        vector = report_search_vector()
        ts_query = web_search_query(query)
        rank = func.ts_rank(vector, ts_query)
        headline = func.ts_headline(
            "english",
            Report.executive_summary,
            ts_query,
            "MaxWords=30, MinWords=12, StartSel=«, StopSel=»",
        )
        condition = vector.op("@@")(ts_query)
        async with self._db.session() as session:
            total = int(
                await session.scalar(select(func.count()).select_from(Report).where(condition)) or 0
            )
            rows = (
                await session.execute(
                    select(Report, ResearchRun, rank.label("rank"), headline.label("snippet"))
                    .join(ResearchRun, ResearchRun.id == Report.run_id)
                    .where(condition)
                    .order_by(rank.desc(), Report.created_at.desc())
                    .limit(limit)
                    .offset(offset)
                )
            ).all()
        return list(rows), total
